import { Request, Response } from "express";
import prisma from "../lib/prisma";
import sharp from "sharp";
import path from "path";
import fs from "fs";
import { isProductCategory, sortByCategory } from "../constants/productCategories";
import { clearTrainingCatalogCache } from "../services/training-catalog.service";
import { invalidateSimulateCaches } from "../services/simulate.service";
import {
  analyzeProductImageFile,
  sanitizeProductText,
} from "../services/productVision.service";

const UPLOADS_DIR = path.resolve(__dirname, "../../uploads");

/** Convert an uploaded image to JPEG (WhatsApp only supports jpeg/png). Returns the new filename. */
async function convertToJpeg(file: Express.Multer.File): Promise<string> {
  const ext = path.extname(file.filename).toLowerCase();
  // Already jpeg/jpg — no conversion needed
  if (ext === ".jpg" || ext === ".jpeg") return file.filename;
  // Already png — WhatsApp supports this too
  if (ext === ".png") return file.filename;

  const newFilename = file.filename.replace(/\.[^.]+$/, ".jpg");
  const inputPath = path.join(UPLOADS_DIR, file.filename);
  const outputPath = path.join(UPLOADS_DIR, newFilename);

  await sharp(inputPath).jpeg({ quality: 85 }).toFile(outputPath);
  // Remove original non-jpeg file
  fs.unlink(inputPath, () => {});
  return newFilename;
}

function parseCategory(value: unknown): string {
  const raw = typeof value === "string" ? value.trim().toLowerCase() : "";
  return isProductCategory(raw) ? raw : "other";
}

// GET /api/admin/products — list all products
export async function listProducts(_req: Request, res: Response): Promise<void> {
  const products = sortByCategory(await prisma.product.findMany());
  res.json({ products });
}

// POST /api/admin/products/scan-image — scan an uploaded image preview and return AI-generated details
export async function scanProductImage(req: Request, res: Response): Promise<void> {
  try {
    if (!req.file) {
      res.status(400).json({ error: "Image file is required" });
      return;
    }

    const filePath = path.join(UPLOADS_DIR, req.file.filename);
    const analysis = await analyzeProductImageFile(filePath);

    res.json({
      success: true,
      analysis,
    });
  } catch (err) {
    console.error("[product-controller] Image scan failed:", err);
    res.status(500).json({
      error: (err as Error).message || "Failed to analyze product image",
    });
  }
}

// POST /api/admin/products/:id/scan-image — scan existing product's image and save generated description
export async function scanExistingProduct(req: Request, res: Response): Promise<void> {
  try {
    const id = String(req.params.id);
    const product = await prisma.product.findUnique({ where: { id } });

    if (!product) {
      res.status(404).json({ error: "Product not found" });
      return;
    }

    if (!product.imageUrl) {
      res.status(400).json({ error: "Product does not have an image uploaded" });
      return;
    }

    const analysis = await analyzeProductImageFile(product.imageUrl);

    // Update product with factual details extracted from the image
    const updated = await prisma.product.update({
      where: { id },
      data: {
        detail: sanitizeProductText(analysis.detail),
        ...(product.category === "other" && analysis.category !== "other"
          ? { category: analysis.category }
          : {}),
      },
    });

    clearTrainingCatalogCache();
    invalidateSimulateCaches();

    res.json({
      success: true,
      product: updated,
      analysis,
    });
  } catch (err) {
    console.error("[product-controller] Existing product scan failed:", err);
    res.status(500).json({
      error: (err as Error).message || "Failed to analyze product image",
    });
  }
}

// POST /api/admin/products — create a product (multipart: image file + JSON fields)
export async function createProduct(req: Request, res: Response): Promise<void> {
  const { name, detail, price, contactNumber, displayOrder, category, autoGenerateDetail } = req.body;
  if (!name?.trim()) {
    res.status(400).json({ error: "Product name is required" });
    return;
  }

  const imageFilename = req.file ? await convertToJpeg(req.file) : null;
  const imageUrl = imageFilename ? `/uploads/${imageFilename}` : null;

  let finalDetail = detail?.trim() ? sanitizeProductText(detail.trim()) : null;

  // If detail was not provided or auto-generation explicitly requested, scan the image
  if (imageUrl && (!finalDetail || autoGenerateDetail === "true" || autoGenerateDetail === true)) {
    try {
      const fullImagePath = path.join(UPLOADS_DIR, imageFilename!);
      const analysis = await analyzeProductImageFile(fullImagePath);
      if (analysis.detail) {
        finalDetail = sanitizeProductText(analysis.detail);
      }
    } catch (scanErr) {
      console.warn("[product-controller] Auto-generate detail on create failed:", (scanErr as Error).message);
    }
  }

  const product = await prisma.product.create({
    data: {
      name: name.trim(),
      category: parseCategory(category),
      detail: finalDetail,
      price: price?.trim() || null,
      imageUrl,
      contactNumber: contactNumber?.trim() || null,
      displayOrder: displayOrder ? parseInt(displayOrder, 10) : 0,
    },
  });
  clearTrainingCatalogCache();
  invalidateSimulateCaches();
  res.status(201).json({ product });
}

// PATCH /api/admin/products/:id — update a product
export async function updateProduct(req: Request, res: Response): Promise<void> {
  const id = String(req.params.id);
  const { name, detail, price, contactNumber, displayOrder, isActive, category, autoGenerateDetail } = req.body;

  const existing = await prisma.product.findUnique({ where: { id } });
  if (!existing) {
    res.status(404).json({ error: "Product not found" });
    return;
  }

  const imageFilename = req.file ? await convertToJpeg(req.file) : undefined;
  const imageUrl = imageFilename ? `/uploads/${imageFilename}` : undefined;

  let finalDetail: string | null | undefined =
    detail !== undefined ? (detail?.trim() ? sanitizeProductText(detail.trim()) : null) : undefined;

  // If a new image was uploaded and auto-generation requested or detail empty
  if (
    imageFilename &&
    (autoGenerateDetail === "true" || autoGenerateDetail === true || (!finalDetail && !existing.detail))
  ) {
    try {
      const fullImagePath = path.join(UPLOADS_DIR, imageFilename);
      const analysis = await analyzeProductImageFile(fullImagePath);
      if (analysis.detail) {
        finalDetail = sanitizeProductText(analysis.detail);
      }
    } catch (scanErr) {
      console.warn("[product-controller] Auto-generate detail on update failed:", (scanErr as Error).message);
    }
  }

  const updated = await prisma.product.update({
    where: { id },
    data: {
      ...(name !== undefined && { name: name.trim() }),
      ...(category !== undefined && { category: parseCategory(category) }),
      ...(finalDetail !== undefined && { detail: finalDetail }),
      ...(price !== undefined && { price: price?.trim() || null }),
      ...(imageUrl !== undefined && { imageUrl }),
      ...(contactNumber !== undefined && { contactNumber: contactNumber?.trim() || null }),
      ...(displayOrder !== undefined && { displayOrder: parseInt(displayOrder, 10) }),
      ...(isActive !== undefined && { isActive: isActive === true || isActive === "true" }),
    },
  });
  clearTrainingCatalogCache();
  invalidateSimulateCaches();
  res.json({ product: updated });
}

// DELETE /api/admin/products/:id — delete a product
export async function deleteProduct(req: Request, res: Response): Promise<void> {
  const id = String(req.params.id);
  const existing = await prisma.product.findUnique({ where: { id } });
  if (!existing) {
    res.status(404).json({ error: "Product not found" });
    return;
  }
  await prisma.product.delete({ where: { id } });
  clearTrainingCatalogCache();
  invalidateSimulateCaches();
  res.json({ message: "Product deleted" });
}
